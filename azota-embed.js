/* Loaded synchronously before lesson code: also supports old iframe URLs. */
(() => {
  'use strict';
  const active = new URLSearchParams(location.search).get('embed') === 'azota' || window.self !== window.top;
  window.AzotaEmbed = Object.freeze({ active });
  if (!active) return;
  document.documentElement.classList.add('azota-embed');
  function otherActivity(anchor) {
    if (anchor.classList.contains('azota-expand')) return false;
    const url = new URL(anchor.href, location.href);
    return url.origin !== location.origin || url.pathname !== location.pathname || url.search !== location.search;
  }
  function markLinks(root = document) {
    root.querySelectorAll('a[href]').forEach(a => {
      if (otherActivity(a)) { a.classList.add('azota-cross-link'); a.setAttribute('aria-hidden','true'); a.tabIndex=-1; }
    });
  }
  // Capture phase also guards links generated by lesson code after startup.
  for (const event of ['click','auxclick']) document.addEventListener(event, e => {
    const a=e.target.closest?.('a[href]');
    if(a && otherActivity(a)){e.preventDefault();e.stopImmediatePropagation();}
  },true);
  document.addEventListener('DOMContentLoaded', () => {
    const toolbar=document.createElement('div'); toolbar.className='azota-toolbar';
    const title=document.createElement('span');title.textContent='Cùng Sóc thử nhé!';
    const expand=document.createElement('a');expand.className='azota-expand';expand.textContent='Mở rộng hoạt động ↗';
    const url=new URL(location.href);url.searchParams.set('embed','azota');expand.href=url.href;expand.target='_blank';expand.rel='noopener noreferrer';
    expand.addEventListener('click',()=>{const current=new URL(location.href);current.searchParams.set('embed','azota');expand.href=current.href;});
    toolbar.append(title,expand);document.body.prepend(toolbar);
    const page=document.body.dataset.page,lesson=document.body.dataset.lesson;
    const note=document.createElement('p');note.className='azota-submit-note';
    note.textContent=lesson==='3'?'Khi xong, sao chép phiếu và chọn đúng mục Q5 trên Azota. Q6 là phần mở rộng.':lesson==='4'?'Khi xong, sao chép báo cáo và chọn đúng mục Q7 trên Azota.':page==='practice'?'Khi xong, chọn đúng mục Q1 trên Azota để nộp câu trả lời.':'Em có thể làm lại ngay tại đây.';
    note.textContent+=' Điểm chính thức do Azota ghi nhận.';
    document.querySelector('main')?.append(note);
    markLinks();
    new MutationObserver(records=>{if(records.some(r=>r.addedNodes.length))markLinks();}).observe(document.body,{childList:true,subtree:true});
    // No resize requests or parent DOM access. The iframe keeps its own scrolling.
  });
})();
